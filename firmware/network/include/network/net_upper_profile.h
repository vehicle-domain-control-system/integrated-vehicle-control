#ifndef NETWORK_NET_UPPER_PROFILE_H
#define NETWORK_NET_UPPER_PROFILE_H
#include "network/net_wire.h"

/* Private storage selection only. Wire48/RX51 and execution HOLD are unchanged.
 * Queue depths, timeout policies and target binding are not selected here. */
#define NET_UPPER_PROFILE_HOST 0
#define NET_UPPER_PROFILE_CIS 1
#define NET_UPPER_PROFILE_CIS_CAN_ONLY 2
#define NET_UPPER_PROFILE_BCM 3
#define NET_UPPER_PROFILE_WINDOW 4
#define NET_UPPER_PROFILE_DOMAIN 5
#define NET_UPPER_PROFILE_VSS 6
#ifndef NETWORK_UPPER_NODE_PROFILE
#define NETWORK_UPPER_NODE_PROFILE NET_UPPER_PROFILE_HOST
#endif

#if NETWORK_UPPER_NODE_PROFILE == NET_UPPER_PROFILE_HOST
#define NET_UPPER_ADMISSION_CAPACITY 48u
#define NET_UPPER_UART_RECEIVER_CAPACITY 2u
#define NET_UPPER_PROFILE_NODE 0u
#elif NETWORK_UPPER_NODE_PROFILE == NET_UPPER_PROFILE_CIS
#define NET_UPPER_ADMISSION_CAPACITY 3u
#define NET_UPPER_UART_RECEIVER_CAPACITY 1u
#define NET_UPPER_PROFILE_NODE NET_WIRE_NODE_CIS
#elif NETWORK_UPPER_NODE_PROFILE == NET_UPPER_PROFILE_CIS_CAN_ONLY
#define NET_UPPER_ADMISSION_CAPACITY 1u
#define NET_UPPER_UART_RECEIVER_CAPACITY 0u
#define NET_UPPER_PROFILE_NODE NET_WIRE_NODE_CIS
#elif NETWORK_UPPER_NODE_PROFILE == NET_UPPER_PROFILE_BCM
#define NET_UPPER_ADMISSION_CAPACITY 4u
#define NET_UPPER_UART_RECEIVER_CAPACITY 0u
#define NET_UPPER_PROFILE_NODE NET_WIRE_NODE_BCM
#elif NETWORK_UPPER_NODE_PROFILE == NET_UPPER_PROFILE_WINDOW
#define NET_UPPER_ADMISSION_CAPACITY 2u
#define NET_UPPER_UART_RECEIVER_CAPACITY 0u
#define NET_UPPER_PROFILE_NODE NET_WIRE_NODE_WINDOW
#elif NETWORK_UPPER_NODE_PROFILE == NET_UPPER_PROFILE_DOMAIN
#define NET_UPPER_ADMISSION_CAPACITY 19u
#define NET_UPPER_UART_RECEIVER_CAPACITY 1u
#define NET_UPPER_PROFILE_NODE NET_WIRE_NODE_DOMAIN
#elif NETWORK_UPPER_NODE_PROFILE == NET_UPPER_PROFILE_VSS
#define NET_UPPER_ADMISSION_CAPACITY 3u
#define NET_UPPER_UART_RECEIVER_CAPACITY 0u
#define NET_UPPER_PROFILE_NODE NET_WIRE_NODE_VSS
#else
#error "Unsupported NETWORK_UPPER_NODE_PROFILE"
#endif
#endif
